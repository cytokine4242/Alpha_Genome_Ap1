#!/usr/bin/env python3
"""Writes the YAML configs for scripts/finetune.py (alphagenome-pytorch): frozen trunk + new heads, LoRA, LoRA + Locon, and full fine-tuning, for the CM and FB tracks.
Paths are given once here; the generated files are plain YAML you can edit.

  python make_configs.py --kind 10bp --bigwig-dir /srv/scratch/.../bigwigs --genome mm10.fa --folds-dir /srv/scratch/.../folds_mouse --work-dir /srv/scratch/.../ft_runs
  python make_configs.py --kind 1bp ...          # after make_insertion_bigwigs.py has produced <Cell>_<Cond>.insertions.bw
  options: --seq-length 131072 (default: centre 128 kb of each fold window; 1048576 = full 1 Mb windows) --conditions YS MAS MAE YE --with-rna --rna-dir DIR --fold FOLD_3 --pilot (1 epoch, 200 train / 40 valid windows)
"""
import argparse
from pathlib import Path

from ft_tracks import CONDITIONS, RNA, atac_file, atac_tracks

ap = argparse.ArgumentParser()
ap.add_argument("--kind", choices=["10bp", "1bp"], required=True, help="target bigWigs: existing 10 bp SeqDepthNorm tracks or 1 bp insertion tracks")
ap.add_argument("--bigwig-dir", required=True)
ap.add_argument("--rna-dir", default=None)
ap.add_argument("--with-rna", action="store_true")
ap.add_argument("--genome", required=True)
ap.add_argument("--folds-dir", required=True, help="output of make_mouse_folds.sh (contains FOLD_k/train.bed, valid.bed, test.bed)")
ap.add_argument("--fold", default="FOLD_3", help="fold whose backbone weights and splits are used (weights must be the matching model_fold_k)")
ap.add_argument("--weights-dir", default="/srv/scratch/wonglab/minh/alphagenome/weights")
ap.add_argument("--work-dir", required=True, help="where runs and checkpoints are written")
ap.add_argument("--metadata", default=None)
ap.add_argument("--out-dir", default=str(Path(__file__).resolve().parents[1] / "configs"))
ap.add_argument("--seq-length", type=int, default=131072, help="131072 (default): the centre 128 kb of each 1 Mb fold window, about 8x cheaper and the length the perturbation runs use; 1048576: full windows, as in Minh's runs")
ap.add_argument("--conditions", nargs="+", default=CONDITIONS)
ap.add_argument("--pilot", action="store_true")
ap.add_argument("--epochs", type=int, default=None, help="override every mode's epochs (not the pilot's 1); the 128 bp probe plateaued by epoch 3 of 15")
a = ap.parse_args()

fold_n = a.fold.split("_")[-1]
weights = f"{a.weights_dir}/model_fold_{fold_n}.safetensors"
res = '"128"' if a.kind == "10bp" else '"1,128"'
atac = [f"{a.bigwig_dir}/{atac_file(a.kind, c, k)}" for c, k, _ in atac_tracks(a.conditions)]
rna = [f"{a.rna_dir or a.bigwig_dir}/{f}" for f in RNA.values()] if a.with_rna else []
train_bed = f"{a.folds_dir}/{a.fold}/train{'_pilot' if a.pilot else ''}.bed"
suffix = ("_pilot" if a.pilot else "") + ("_rna" if a.with_rna else "")
run_tag = f"{a.kind}_{a.fold.lower()}_{a.seq_length // 1024}kb" + suffix          # unique per target kind, fold and length, so 'resume: auto' never picks up another run's checkpoint
val_bed = f"{a.folds_dir}/{a.fold}/valid{'_pilot' if a.pilot else ''}.bed"

MODES = {   # lr, epochs, warmup, extra lines, delta checkpoints work for everything except full
    "probe": dict(mode="linear-probe", lr="0.001", epochs=15, warmup=500, extra=[], delta=True),
    "lora": dict(mode="lora", lr="0.0001", epochs=8, warmup=100, extra=["lora_rank: 8", "lora_alpha: 16", 'lora_targets: "q_proj,v_proj"'], delta=True),
    "lora_locon": dict(mode="lora+locon", lr="0.0001", epochs=8, warmup=100,
                       extra=["lora_rank: 8", "lora_alpha: 16", 'lora_targets: "q_proj,v_proj"', "locon_rank: 4", "locon_alpha: 1", 'locon_targets: "down_blocks.4,down_blocks.5"'], delta=True),
    "full": dict(mode="full", lr="0.00001", epochs=5, warmup=200, extra=[], delta=False),
}


def yaml_text(name, m):
    epochs = 1 if a.pilot else (a.epochs or m["epochs"])
    lines = [f"# {name}: {m['mode']} fine-tuning of AlphaGenome on mouse cardiomyocyte and fibroblast ATAC ({a.kind} targets), generated by make_configs.py",
             f"genome: {a.genome}", f"pretrained_weights: {weights}", f"train_bed: {train_bed}", f"val_bed: {val_bed}",
             f"sequence_length: {a.seq_length}", "organism: mouse"]
    if a.metadata:
        lines.append(f"track_metadata: {a.metadata}")
    lines += [f"output_dir: {a.work_dir}", f"run_name: {name}_{run_tag}", "save_every: 1", "cache_genome: true", "cache_signals: false", "dtype: bfloat16", "gradient_checkpointing: true",
              "use_amp: true", "num_workers: 4", f"mode: {m['mode']}", f"epochs: {epochs}", "batch_size: 4", "gradient_accumulation_steps: 8", f"lr: {m['lr']}", "weight_decay: 0.1",
              f"warmup_steps: {10 if a.pilot else m['warmup']}", "lr_schedule: cosine", "max_grad_norm: 1.0", "positional_weight: 5.0", "count_weight: 1.0", "compile: false", "wandb: false", "log_every: 10",
              "resume: auto", f"save_delta: {'true' if m['delta'] else 'false'}", f"no_full_checkpoint: {'true' if m['delta'] else 'false'}", "seed: 42", f"resolutions: {res}"] + m["extra"]
    lines += ["modalities:", "  atac:", "    bigwig:"] + [f"      - {p}" for p in atac] + ["    task_weight: 1.0"]
    if rna:
        lines += ["  rna_seq:", "    bigwig:"] + [f"      - {p}" for p in rna] + ['    resolutions: "128"', "    task_weight: 0.3"]
    return "\n".join(lines) + "\n"


out = Path(a.out_dir)
out.mkdir(parents=True, exist_ok=True)
for name, m in MODES.items():
    p = out / f"{name}_{run_tag}.yaml"
    p.write_text(yaml_text(name, m))
    print("wrote", p)
